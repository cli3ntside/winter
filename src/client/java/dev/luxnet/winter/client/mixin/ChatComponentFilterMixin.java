package dev.luxnet.winter.client.mixin;

import dev.luxnet.winter.client.visuals.ChatFilter;
import net.minecraft.client.GuiMessageTag;
import net.minecraft.client.gui.components.ChatComponent;
import net.minecraft.network.chat.Component;
import net.minecraft.network.chat.MessageSignature;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(value = ChatComponent.class, priority = 500)
public abstract class ChatComponentFilterMixin {
	@Inject(method = "addMessage(Lnet/minecraft/network/chat/Component;Lnet/minecraft/network/chat/MessageSignature;Lnet/minecraft/client/GuiMessageTag;)V",
		at = @At("HEAD"), cancellable = true)
	private void winter$filterChatNoise(Component message, MessageSignature signature, GuiMessageTag tag, CallbackInfo ci) {
		if (ChatFilter.shouldHide(message)) ci.cancel();
	}
}
